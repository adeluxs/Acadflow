<h2>The accounting equation</h2>
<p><strong>Assets = Liabilities + Equity</strong></p>
<ul>
<li><strong>Assets</strong> are resources the business owns or controls that will bring future benefit: cash, equipment, inventory, money owed by customers (receivables).</li>
