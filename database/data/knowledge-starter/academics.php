<p>Most students do not fail because they are not smart enough. They fail because they start too late, read passively, and arrive at the exam hall tired. This plan gives you a simple structure for the last fourteen days before your exams. Adjust it to your timetable, but keep the principles.</p>

<h2>The two ideas behind the plan</h2>
<p><strong>Active recall.</strong> Reading your notes again feels productive, but it mostly builds familiarity, not memory. Closing the book and trying to write down what you remember, or answering questions without looking, is what actually strengthens memory.</p>
<p><strong>Spaced practice.</strong> You remember more when you revisit a topic several times with gaps in between than when you study it once for many hours. That is why this plan returns to every course more than once.</p>

<h2>Before day 1: make your list</h2>
<ul>
<li>Write down every course you will write, its exam date and the topics in the course outline.</li>
<li>Mark each topic green (I understand it), amber (partly) or red (I don't understand it yet).</li>
<li>Collect past questions for each course and keep them in one folder.</li>
</ul>

<h2>Days 1 to 4: fix the red topics</h2>
<p>Spend these days on the topics you marked red, starting with the course you write first. For each topic, read the notes once with full attention, then close them and write a one-page summary from memory. Check what you missed and correct it in a different colour. The corrections show you exactly where your gaps are.</p>

<h2>Days 5 to 8: practise with questions</h2>
<p>Now move from understanding to answering. For each course, attempt at least one full set of past questions. Do the first set with your notes open if you need to, and the next set without notes. After each attempt, mark yourself honestly and write down every question you could not answer. Those questions become your to-do list for the next day.</p>

<h2>Days 9 to 11: mixed revision</h2>
<p>Mix courses and topics within a day instead of spending a whole day on one course. Mixing feels harder, but it trains you to recognise what a question is asking, which is exactly what you must do in the exam hall. Use flashcards for definitions, formulas and key dates, and test yourself in short sessions of 25 to 40 minutes with a 5 minute break.</p>

<h2>Days 12 and 13: timed practice</h2>
<p>Write at least one past paper per course under exam conditions: timed, no phone, no notes. This shows you whether you can finish in time and which question types slow you down. Spend the second half of each day reviewing mistakes only.</p>

<h2>Day 14: light review and rest</h2>
<p>Go through your one-page summaries and flashcards. Do not start new topics. Prepare your writing materials, ID card and exam docket, and sleep early. A rested brain recalls far better than a brain that crammed until 3am.</p>

<h2>Daily habits that make the plan work</h2>
<ul>
<li>Study at the same times each day so it becomes routine.</li>
<li>Keep your phone in another room or on airplane mode during study blocks.</li>
