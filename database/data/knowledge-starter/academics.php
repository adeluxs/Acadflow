<p>Supply and demand is the foundation of introductory economics. Once you understand it, a large part of ECO 101 becomes much easier. This guide explains the core ideas with everyday Nigerian examples.</p>

<h2>Demand</h2>
<p><strong>Demand</strong> is the quantity of a good that buyers are willing and able to buy at different prices over a period of time. Both conditions matter: wanting a car is not demand unless you can pay for it.</p>
<p>The <strong>law of demand</strong> states that, other things being equal, as the price of a good rises, the quantity demanded falls, and as the price falls, the quantity demanded rises. If the price of a plate of rice at your campus canteen rises from ₦800 to ₦1,200, students buy fewer plates and switch to cheaper meals.</p>
<p>A <strong>demand curve</strong> slopes downward from left to right on a graph with price on the vertical axis and quantity on the horizontal axis.</p>

<h2>Supply</h2>
<p><strong>Supply</strong> is the quantity that sellers are willing and able to offer at different prices. The <strong>law of supply</strong> states that, other things being equal, a higher price leads to a higher quantity supplied, because selling becomes more profitable. The supply curve slopes upward.</p>

<h2>Movement along a curve versus a shift</h2>
<p>This distinction appears in almost every ECO 101 exam.</p>
<ul>
<li>A <strong>change in the good's own price</strong> causes a <strong>movement along</strong> the curve. This is called a change in quantity demanded or quantity supplied.</li>
<li>A <strong>change in any other factor</strong> causes the whole curve to <strong>shift</strong>. This is called a change in demand or a change in supply.</li>
</ul>
<p><strong>Factors that shift demand:</strong> income, prices of related goods (substitutes and complements), tastes and preferences, population and expectations about future prices.</p>
<p><strong>Factors that shift supply:</strong> cost of production (for example fuel or electricity), technology, number of sellers, government taxes or subsidies, weather for agricultural goods, and expectations.</p>
<p>Example: if the price of diesel rises, it costs more to run generators and transport goods, so the supply curve of many products shifts to the left.</p>

<h2>Substitutes and complements</h2>
<p><strong>Substitutes</strong> can replace each other, like garri and rice. If rice becomes expensive, demand for garri rises. <strong>Complements</strong> are used together, like cars and petrol. If petrol becomes very expensive, demand for cars that use a lot of fuel falls.</p>

<h2>Equilibrium</h2>
<p>The <strong>equilibrium</strong> is the price at which quantity demanded equals quantity supplied, where the two curves cross. At this price the market clears: there is no shortage and no surplus.</p>
<ul>
<li>If the price is <strong>above</strong> equilibrium, sellers offer more than buyers want. The result is a <strong>surplus</strong>, and sellers lower prices to clear their stock.</li>
<li>If the price is <strong>below</strong> equilibrium, buyers want more than sellers offer. The result is a <strong>shortage</strong>, queues form, and prices tend to rise.</li>
</ul>

<h2>Price controls</h2>
<p>A <strong>price ceiling</strong> is a maximum legal price set below equilibrium. It can help buyers in the short term but often causes shortages and black markets. A <strong>price floor</strong> is a minimum price set above equilibrium, such as a minimum wage in the labour market, and can cause a surplus.</p>

