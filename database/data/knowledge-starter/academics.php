<li><strong>Sample variance</strong> (divide by n − 1): 32 ÷ 7 ≈ 4.57. Sample standard deviation ≈ <strong>2.14</strong>.</li>
</ul>
<p>Use n when your data is the whole population and n − 1 when it is a sample from a larger population. Check which one your lecturer uses, and always state it.</p>

<h2>Which measure should you use?</h2>
<ul>
<li>Use the <strong>mean</strong> for data without extreme values.</li>
<li>Use the <strong>median</strong> when there are outliers or the data is skewed.</li>
<li>Use the <strong>mode</strong> for categories, such as the most common department in a class.</li>
</ul>

